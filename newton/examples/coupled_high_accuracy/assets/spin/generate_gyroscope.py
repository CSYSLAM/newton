"""Generate a balanced demonstration flywheel and spindle without external mesh dependencies."""

from pathlib import Path

import numpy as np
from pxr import Gf, Usd, UsdGeom, Vt


def geometry(segments=96):
    # The spindle and flywheel share rings, keeping a single closed boundary and a well-defined inertia.
    profile = ((-0.017, 0.0015), (-0.004, 0.0025), (-0.003, 0.014),
               (0.003, 0.014), (0.004, 0.0025), (0.018, 0.0025))
    angle = np.arange(segments) * (2.0 * np.pi / segments)
    points = []
    for height, radius in profile:
        # Shallow balanced flutes make axial rotation visible even without a texture.
        radii = radius * (1.0 + 0.025 * np.cos(12.0 * angle)) if radius == 0.014 else np.full(segments, radius)
        points.extend(zip(radii * np.cos(angle), radii * np.sin(angle), np.full(segments, height)))
    bottom, top = len(points), len(points) + 1
    points.extend(((0.0, 0.0, -0.020), (0.0, 0.0, 0.020)))
    faces = []
    for i in range(segments):
        j = (i + 1) % segments
        faces.append((bottom, j, i))
        for layer in range(len(profile) - 1):
            a, b = layer * segments + i, layer * segments + j
            c, d = b + segments, a + segments
            faces.extend(((a, b, c), (a, c, d)))
        last = (len(profile) - 1) * segments
        faces.append((last + i, last + j, top))
    return np.asarray(points, dtype=np.float32), np.asarray(faces, dtype=np.int32)


def main():
    path = Path(__file__).with_name("Gyroscope.usd")
    points, faces = geometry()
    stage = Usd.Stage.CreateNew(str(path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    root = UsdGeom.Xform.Define(stage, "/root")
    stage.SetDefaultPrim(root.GetPrim())
    mesh = UsdGeom.Mesh.Define(stage, "/root/Gyroscope")
    mesh.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(points))
    mesh.CreateFaceVertexCountsAttr([3] * len(faces))
    mesh.CreateFaceVertexIndicesAttr(Vt.IntArray.FromNumpy(faces.ravel()))
    mesh.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
    mesh.CreateDisplayColorAttr([Gf.Vec3f(0.28, 0.48, 0.68)])
    mesh.CreateExtentAttr(Vt.Vec3fArray.FromNumpy(np.stack((points.min(axis=0), points.max(axis=0)))))
    stage.SetMetadata("comment", "Procedural flywheel generated by assets/spin/generate_gyroscope.py.")
    stage.GetRootLayer().Save()
    print(path)


if __name__ == "__main__":
    main()
