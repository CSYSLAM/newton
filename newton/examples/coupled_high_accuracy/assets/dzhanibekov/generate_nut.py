"""Generate the self-contained demonstration wing nut; no original private mesh is required."""

from pathlib import Path

import numpy as np
from pxr import Gf, Usd, UsdGeom, Vt


def geometry(segments=128):
    angle = np.arange(segments) * (2.0 * np.pi / segments)
    # A thin XZ profile keeps three distinct moments, with the intermediate axis along local Z.
    radius = 0.008 + 0.013 * np.cos(angle) ** 8 + 0.005 * np.sin(angle) ** 4
    outer = np.column_stack((radius * np.cos(angle), radius * np.sin(angle)))
    inner = np.column_stack((0.003 * np.cos(angle), 0.003 * np.sin(angle)))
    points = []
    for depth in (-0.002, 0.002):
        for ring in (outer, inner):
            points.extend((x, depth, z) for x, z in ring)
    faces = []
    for i in range(segments):
        j = (i + 1) % segments
        a, b = i + 2 * segments, j + 2 * segments
        quads = (
            (i, j, j + segments, i + segments),
            (a, a + segments, b + segments, b),
            (i, a, b, j),
            (i + segments, j + segments, b + segments, a + segments),
        )
        for p, q, r, s in quads:
            faces.extend(((p, q, r), (p, r, s)))
    return np.asarray(points, dtype=np.float32), np.asarray(faces, dtype=np.int32)


def main():
    path = Path(__file__).with_name("Nut.usd")
    points, faces = geometry()
    stage = Usd.Stage.CreateNew(str(path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    root = UsdGeom.Xform.Define(stage, "/root")
    stage.SetDefaultPrim(root.GetPrim())
    mesh = UsdGeom.Mesh.Define(stage, "/root/nut")
    mesh.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(points))
    mesh.CreateFaceVertexCountsAttr([3] * len(faces))
    mesh.CreateFaceVertexIndicesAttr(Vt.IntArray.FromNumpy(faces.ravel()))
    mesh.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
    mesh.CreateDisplayColorAttr([Gf.Vec3f(0.68, 0.72, 0.78)])
    mesh.CreateExtentAttr(Vt.Vec3fArray.FromNumpy(np.stack((points.min(axis=0), points.max(axis=0)))))
    stage.SetMetadata("comment", "Procedural wing nut generated by assets/dzhanibekov/generate_nut.py.")
    stage.GetRootLayer().Save()
    print(path)


if __name__ == "__main__":
    main()
